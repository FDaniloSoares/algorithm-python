# 4. Métodos que você deve conhecer
# Operação	Exemplo	Para que serve
# Acessar	d["a"]	Obter o valor da chave
# Acessar com padrão	d.get("a", 0)	Evitar KeyError
# Adicionar/atualizar	d["a"] = 10	Gravar um valor
# Verificar chave	"a" in d	Verificar se existe
# Obter chaves	d.keys()	Visualizar as chaves
# Obter valores	d.values()	Visualizar os valores
# Obter pares	d.items()	Percorrer chave e valor
# Remover	d.pop("a")	Remover e retornar o valor
# Limpar	d.clear()	Esvaziar o dicionário
# Quantidade	len(d)	Contar as entradas
# Copiar	d.copy()	Criar uma cópia superficial